export const thaiLabel = (value: string): string => labels[value] ?? value;

export function thaiContent(data: PortfolioData): PortfolioData {
  const about = data.about;
  return { ...data, about: { ...about,
    location: thaiLabel(about.location), status: thaiLabel(about.status),
    interests: about.interests?.map(thaiLabel),
    expertise: about.expertise?.map((item) => ({ ...item, area: thaiLabel(item.area) })),
    experience: about.experience?.map((item) => ({ ...item, role: thaiLabel(item.role), company: thaiLabel(item.company) })),
  },
    projects: data.projects.map((item) => ({ ...item, description: thaiLabel(item.description) })),
    certificates: data.certificates?.map((item) => ({ ...item, description: thaiLabel(item.description) })),
  };
}
