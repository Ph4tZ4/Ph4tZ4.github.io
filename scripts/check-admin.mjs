import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { runInNewContext } from 'node:vm';
import { collections, categories, escape, imageUrl, items, validData } from '../admin-model.js';
const manager = runInNewContext(`${await readFile(new URL('../data-manager.js', import.meta.url),'utf8')}; DataManager;`);
const data = JSON.parse(JSON.stringify(manager.getDefaultData()));
assert.ok(validData(data), 'Existing data remains compatible');
for (const key of Object.keys(collections)) assert.ok(Array.isArray(items(data,key)), `${key} can be edited`);
const edited = structuredClone(data);
const old = items(edited,'projects')[0];
items(edited,'projects')[0] = {...old,title:'ผลงานใหม่'};
assert.equal(edited.projects[0].image,old.image,'Editing preserves image URLs');
assert.notEqual(data.projects[0].title,edited.projects[0].title,'Editing a draft does not mutate original content');
assert.ok(validData({...data,certificates:undefined}),'Legacy backups may omit certificates');
for (const invalid of [null,{}, {...data,skills:{}},{...data,projects:[null]}, {...data,about:{...data.about,interests:[{}]}}, {...data,about:[]}]) assert.equal(validData(invalid),false,'Reject malformed imports');
assert.equal(imageUrl('javascript:alert(1)'), '');
assert.equal(imageUrl('data:text/html,test'), '');
assert.equal(imageUrl('images/portrait.jpg'), 'images/portrait.jpg');
assert.equal(imageUrl('https://example.com/photo.png'), 'https://example.com/photo.png');
assert.equal(escape('<img src=x onerror="alert(1)">'), '&lt;img src=x onerror=&quot;alert(1)&quot;&gt;');
assert.ok(categories.Frontend,'Stored category IDs remain compatible');
const dashboard = await readFile(new URL('../dashboard.html',import.meta.url),'utf8');
assert.match(dashboard, /<dialog id="editor"/);
assert.doesNotMatch(dashboard, /onclick=|generateMockData|data-table/);
const app = await readFile(new URL('../admin-app.js',import.meta.url),'utf8');
assert.match(app, /localStorage.setItem\(draftKey, JSON.stringify\(data\)\)/,'Drafts are stored separately from live data');
console.log('Admin checks passed: legacy data compatibility, collections, backup validation, safe rendering and draft storage.');
